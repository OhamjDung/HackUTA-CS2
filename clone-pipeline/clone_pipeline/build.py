"""Build one clone from match recordings.

    uv run python -m clone_pipeline.build --player donk --demos ../data/demos --holdout 2393242

Writes, under --out (default ../clones):
    <clone_id>.json                      the clone profile (the format match-service reads, plus more fields)
    <clone_id>/botprofile.txt            an entry for the bot personality file (botprofile.db)
    <clone_id>/buy_plan.json             purchase list per side and purchase type
    <clone_id>/grenades.json             every grenade throw
    <clone_id>/routes/<side>/<name>.json.br   route segments as CS2-Bot-Controller recordings
"""

import argparse
import json
import re
from datetime import datetime, timezone
from pathlib import Path

from . import habits
from .parse import Match, load_match
from .recording import write_recording
from .routes import Segment, cut_segments
from .similarity import compare


def stats_block(matches: list[Match], segments: list[Segment]) -> dict:
    """The numbers that similarity.compare() needs, for one set of matches."""
    return {
        "rounds": {side: sum(int((m.rounds["side"] == side).sum()) for m in matches) for side in ("T", "CT")},
        "positions": habits.positions(matches, top=40),
        "route_shares": habits.route_shares(segments),
        "seconds_to_first_contact": habits.seconds_to_first_contact(matches),
    }


def botprofile_entry(clone_id: str, name: str, aggression_value: float, weapons: list[str]) -> str:
    """Text to add to botprofile.db. The syntax follows the file shipped by CS2-Bot-Improver:
    a Template block, then a bot entry that uses it. NOT TESTED in the game."""
    template = "Clone_" + re.sub(r"\W", "_", clone_id)
    lines = [
        f"// Clone of {name}. Generated by clone-pipeline. Skill 100 is a base-bot setting, not a measured player rating.",
        f"Template {template}",
        "\tSkill = 100",
        f"\tAggression = {round(aggression_value * 100)}",
        "\tTeamwork = 100",
    ]
    lines += [f"\tWeaponPreference = {weapon}" for weapon in weapons]
    lines += ["End", "", f"{template} {name}", "End", ""]
    return "\n".join(lines)


def build_clone(player: str, demo_paths: list[Path], holdout_ids: set[str], clone_id: str, out_dir: Path,
                source: str = "pro") -> dict:
    matches = [load_match(path, player) for path in demo_paths]
    train = [m for m in matches if m.match_id not in holdout_ids]
    held = [m for m in matches if m.match_id in holdout_ids]
    if not train:
        raise ValueError("No recordings left to build from after removing the held-back ones.")

    if len({m.steam_id for m in matches}) != 1:
        raise ValueError("All recordings must resolve to the same Steam ID; names alone are not identity.")

    train_segments = [s for m in train for s in cut_segments(m)]
    held_segments = [s for m in held for s in cut_segments(m)]

    bundle = out_dir / clone_id
    routes: dict[str, list[dict]] = {"T": [], "CT": []}
    shares = habits.route_shares(train_segments)
    for seg in train_segments:
        name = f"{clone_id}_{seg.side.lower()}_{seg.match_id}_r{seg.round:02d}"
        rel = Path("routes") / seg.side / f"{name}.json.br"
        tick_count = write_recording(seg.ticks, bundle / rel)
        first = seg.ticks.iloc[0]
        routes[seg.side].append({
            "recording": name,                 # the name to pass to "!replay <slot> <name>"
            "file": f"{clone_id}/{rel.as_posix()}",
            "source": "recorded",
            "route_key": seg.route_key,
            "label": seg.label,
            "buy_type": seg.buy_type,
            "match_id": seg.match_id, "round": seg.round,
            "seconds": seg.seconds, "ticks": tick_count, "end_reason": seg.end_reason,
            "start": [round(float(first["X"]), 1), round(float(first["Y"]), 1), round(float(first["Z"]), 1)],
        })

    aggr = habits.aggression(train, train[0].steam_id)
    weapons = habits.weapon_preferences(train)
    plan = habits.buy_plan(train)
    throws = habits.grenade_throws(train)
    train_stats = stats_block(train, train_segments)

    similarity = None
    if held:
        similarity = {
            "what": "The player's building matches compared with the player's own held-back matches. "
                    "This is the ceiling: how alike the player is to themselves.",
            "held_back_matches": sorted(m.match_id for m in held),
            "player_vs_self": compare(train_stats, stats_block(held, held_segments)),
        }

    name = train[0].player_name
    profile = {
        # Fields that match-service/sample_clones/*.json already uses.
        "clone_id": clone_id,
        "display_name": name,
        "source": source,
        "reaction_ms": None,   # not measured: recordings do not say when an enemy became visible
        "aim_skill": 1.0,      # maximum base-bot setting; not a measurement of the player's aim
        "aggression": aggr["value"],
        "weapons": weapons,
        "positions": habits.positions(train),
        "model": None,         # set when the generating model has an identity vector for this player
        # Fields added by the clone pipeline (proposed in SPEC.md section 5.4).
        "map": train[0].map_name,
        "steam_id": train[0].steam_id,
        "aggression_detail": aggr,
        "route_shares": shares,
        "routes": routes,
        "buy_plan": plan,
        "files": {
            "botprofile": f"{clone_id}/botprofile.txt",
            "buy_plan": f"{clone_id}/buy_plan.json",
            "grenades": f"{clone_id}/grenades.json",
        },
        "grenade_throws": len(throws),
        "seconds_to_first_contact": train_stats["seconds_to_first_contact"],
        "source_games": [{"match_id": m.match_id, "file": m.file_name, "rounds": len(m.rounds)} for m in train],
        "rounds": train_stats["rounds"],
        "similarity": similarity,
        "built_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }

    bundle.mkdir(parents=True, exist_ok=True)
    (bundle / "botprofile.txt").write_text(botprofile_entry(clone_id, name, aggr["value"], weapons), encoding="utf-8")
    (bundle / "buy_plan.json").write_text(json.dumps(plan, indent=2), encoding="utf-8")
    (bundle / "grenades.json").write_text(json.dumps(throws, indent=1), encoding="utf-8")
    (bundle / "stats.json").write_text(json.dumps(train_stats, indent=1), encoding="utf-8")
    (out_dir / f"{clone_id}.json").write_text(json.dumps(profile, indent=2), encoding="utf-8")
    return profile


def main() -> None:
    ap = argparse.ArgumentParser(description="Build one clone from match recordings (.dem files).")
    ap.add_argument("--player", required=True, help="the player's name as it appears in the recordings")
    ap.add_argument("--demos", required=True, type=Path, help="a .dem file or a folder of .dem files")
    ap.add_argument("--holdout", nargs="*", default=[], help="match IDs to keep out of the clone, for scoring")
    ap.add_argument("--clone-id", help="default: <player>_v1")
    ap.add_argument("--source", default="pro", choices=["pro", "user"])
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[2] / "clones")
    args = ap.parse_args()

    paths = sorted(args.demos.glob("*.dem")) if args.demos.is_dir() else [args.demos]
    clone_id = args.clone_id or f"{args.player.lower()}_v1"
    profile = build_clone(args.player, paths, set(args.holdout), clone_id, args.out, args.source)

    print(f"Built {clone_id} from {len(profile['source_games'])} recordings, rounds {profile['rounds']}")
    print(f"  aggression {profile['aggression']}  ({profile['aggression_detail']})")
    print(f"  weapons {profile['weapons']}")
    for side in ("T", "CT"):
        print(f"  {side}: {len(profile['routes'][side])} route segments; shares {profile['route_shares'].get(side)}")
    if profile["similarity"]:
        print(f"  player vs own held-back matches: {json.dumps(profile['similarity']['player_vs_self'])}")


if __name__ == "__main__":
    main()
